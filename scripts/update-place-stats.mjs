import { writeFile } from "node:fs/promises";

const PLACE_ID = "ChIJTyoE7NlzGZURHlAt9IQVcGE";
const API_KEY = process.env.GOOGLE_PLACES_API_KEY;

if (!API_KEY) {
  console.error("Missing GOOGLE_PLACES_API_KEY");
  process.exit(1);
}

const response = await fetch(
  `https://places.googleapis.com/v1/places/${PLACE_ID}?languageCode=pt-BR`,
  {
    headers: {
      "X-Goog-Api-Key": API_KEY,
      "X-Goog-FieldMask": "rating,userRatingCount",
    },
  },
);

if (!response.ok) {
  const body = await response.text();
  console.error(`Google Places API failed: ${response.status} ${body}`);
  process.exit(1);
}

const data = await response.json();
const rating = Number(data.rating);
const userRatingCount = Number(data.userRatingCount);

if (!Number.isFinite(rating) || !Number.isInteger(userRatingCount)) {
  console.error("Unexpected Google Places response", data);
  process.exit(1);
}

const updatedAt = new Date().toISOString().slice(0, 10);
const output = `// AUTO-GENERATED by scripts/update-place-stats.mjs.
// Do not edit manually; the weekly GitHub Action refreshes these values.
export const GOOGLE_PLACE_STATS = {
  rating: ${JSON.stringify(rating)},
  userRatingCount: ${JSON.stringify(userRatingCount)},
  updatedAt: ${JSON.stringify(updatedAt)},
} as const;
`;

await writeFile("src/lib/place-stats.generated.ts", output, "utf8");
console.log(`Updated Google rating: ${rating} / ${userRatingCount} reviews`);
